/**
 * Every `--color-*` palette value Kumo and Tailwind define in oklch, rewritten as the
 * exact sRGB hex it renders as — written to src/palette-hex.css, which the page loads
 * after Tailwind. Same colours, nothing visual changes.
 *
 * ⚠ WHY: THE ACCESSIBILITY GATE COULD NOT READ THE PAGE. Chrome hands a neutral oklch
 *   colour back as `oklch(0.97 0 none)` — "no hue" — and axe cannot evaluate contrast
 *   on it, so it files every text element as "needs further review", which pa11y counts
 *   as an error: 92 of them in each palette on white-on-black text measuring ~18:1. A
 *   gate that cannot measure the page is a page whose contrast is unmeasured, and
 *   switching the check off would hide the next real failure the same way. Hex is a
 *   colour every checker reads.
 *
 * Runs on every build, from the installed packages — so a Kumo or Tailwind update
 * cannot leave a stale copy of their palette behind.
 */
import { readFileSync, readdirSync, writeFileSync } from 'node:fs';
import { createRequire } from 'node:module';
import { dirname, join } from 'node:path';

const require = createRequire(import.meta.url);
const kumoStyles = join(dirname(require.resolve('@cloudflare/kumo/package.json')), 'dist', 'styles');
const sources = [
  join(dirname(require.resolve('tailwindcss/package.json')), 'theme.css'),
  ...readdirSync(kumoStyles).filter((f) => f.endsWith('.css') && !f.includes('standalone')).map((f) => join(kumoStyles, f)),
];

/* OKLCH → sRGB, per CSS Color 4: OKLab, then LMS, then linear sRGB, then the sRGB curve. */
function oklchToHex(l, c, h) {
  const hr = (h * Math.PI) / 180;
  const a = c * Math.cos(hr);
  const b = c * Math.sin(hr);
  const l_ = (l + 0.3963377774 * a + 0.2158037573 * b) ** 3;
  const m_ = (l - 0.1055613458 * a - 0.0638541728 * b) ** 3;
  const s_ = (l - 0.0894841775 * a - 1.291485548 * b) ** 3;
  const lin = [
    4.0767416621 * l_ - 3.3077115913 * m_ + 0.2309699292 * s_,
    -1.2684380046 * l_ + 2.6097574011 * m_ - 0.3413193965 * s_,
    -0.0041960863 * l_ - 0.7034186147 * m_ + 1.707614701 * s_,
  ];
  return '#' + lin
    .map((v) => Math.min(1, Math.max(0, v))) // clip to the sRGB gamut, as a browser does on an sRGB screen
    .map((v) => (v <= 0.0031308 ? 12.92 * v : 1.055 * v ** (1 / 2.4) - 0.055))
    .map((v) => Math.round(v * 255).toString(16).padStart(2, '0'))
    .join('');
}

const num = (s) => (s.endsWith('%') ? parseFloat(s) / 100 : parseFloat(s));
const found = new Map();
for (const file of sources) {
  const css = readFileSync(file, 'utf8');
  /* Opaque oklch only: a value with an alpha is a tint layered over something, and
     rewriting it would change what it composites onto. */
  for (const m of css.matchAll(/(--color-[a-z0-9-]+):\s*oklch\(\s*([\d.]+%?)\s+([\d.]+%?)\s+([\d.]+|none)\s*\)/g)) {
    const [, name, l, c, h] = m;
    found.set(name, oklchToHex(num(l), c.endsWith('%') ? parseFloat(c) * 0.004 : parseFloat(c), h === 'none' ? 0 : parseFloat(h)));
  }
  /* Kumo also names colours it never defines, only as a fallback — var(--color-kumo-neutral-25,
     oklch(98.75% 0 0)) — so the fallback is what renders. Define those too, or the canvas and
     every surface keep the value the gate cannot read. */
  for (const m of css.matchAll(/var\((--color-[a-z0-9-]+),\s*oklch\(\s*([\d.]+%?)\s+([\d.]+%?)\s+([\d.]+|none)\s*\)\s*\)/g)) {
    const [, name, l, c, h] = m;
    if (!found.has(name)) found.set(name, oklchToHex(num(l), c.endsWith('%') ? parseFloat(c) * 0.004 : parseFloat(c), h === 'none' ? 0 : parseFloat(h)));
  }
}
if (found.size < 50) throw new Error(`only ${found.size} palette colours found — Kumo or Tailwind moved their theme files; this would ship oklch the gate cannot read`);

writeFileSync(
  new URL('../src/palette-hex.css', import.meta.url),
  `/* GENERATED by scripts/hex-palette.mjs on every build — do not edit. Why: that file's header. */\n:root, :host {\n${[...found].sort().map(([n, v]) => `  ${n}: ${v};`).join('\n')}\n}\n`,
);
console.log(`palette-hex.css: ${found.size} colours as hex`);
